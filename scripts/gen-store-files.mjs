/* Writes the store's track list (id -> title + file in R2) into the two
   serverless functions that need it: api/create-checkout.ts and
   api/webhook.ts. Runs before every build (npm "prebuild"), so the list
   always matches src/catalog.ts.

   Why: checkout used to take the file names from the browser and the webhook
   signed whatever it was given, so an edited request could pay $3 and get a
   download link for any file in the bucket. Now the server decides which
   file belongs to each track. The list is written into each function rather
   than imported, because Vercel bundles each api/ file on its own here. */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const catalog = readFileSync(new URL('src/catalog.ts', root), 'utf8');
const start = catalog.indexOf('export const defaultCatalog');
const body = catalog.slice(start, catalog.indexOf('];', start));

const tracks = {};
for (const obj of body.match(/\{[^{}]*\}/g) ?? []) {
  const id = obj.match(/\bid:\s*(\d+)/)?.[1];
  const title = obj.match(/\btitle:\s*"((?:[^"\\]|\\.)*)"/)?.[1];
  const file = obj.match(/\br2FileName:\s*"((?:[^"\\]|\\.)*)"/)?.[1];
  if (!id || !title) throw new Error(`gen-store-files: can't read a track in src/catalog.ts: ${obj.slice(0, 80)}`);
  // Same fallback the store has always used for a track with no file name.
  tracks[id] = { title, file: file ?? `${id}.mp3` };
}
const count = Object.keys(tracks).length;
if (count < 10) throw new Error(`gen-store-files: only ${count} tracks found; refusing to write`);

const block = `// <store-files> generated by scripts/gen-store-files.mjs from src/catalog.ts; do not edit
const TRACKS: Record<string, { title: string; file: string }> = ${JSON.stringify(tracks, null, 2)};
// </store-files>`;

for (const f of ['api/create-checkout.ts', 'api/webhook.ts']) {
  const url = new URL(f, root);
  const src = readFileSync(url, 'utf8');
  const re = /\/\/ <store-files>[\s\S]*?\/\/ <\/store-files>/;
  if (!re.test(src)) throw new Error(`gen-store-files: no <store-files> markers in ${f}`);
  writeFileSync(url, src.replace(re, block));
}
console.log(`gen-store-files: ${count} tracks written to api/create-checkout.ts and api/webhook.ts`);
